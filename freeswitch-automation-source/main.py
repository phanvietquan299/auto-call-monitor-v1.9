# 1. CẤU HÌNH HỆ THỐNG
# ==========================================
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
CREDENTIALS_FILE = os.path.join(BASE_DIR, "credentials.json")

SPREADSHEET_NAME = "PhoneReplace"

FUSION_NODES = {
    "FS01": "10.10.101.176",
    "FS02": "10.10.101.177",
    "FS03": "10.10.101.178"
}

SSH_USER = "root"
SSH_KEY_PATH = "/root/.ssh/id_rsa"
REMOTE_LUA_PATH = "/usr/share/freeswitch/scripts/caller_ids.lua"

TELEGRAM_BOT_TOKEN = os.environ.get("TELEGRAM_BOT_TOKEN", "")
TELEGRAM_CHAT_ID = os.environ.get("TELEGRAM_CHAT_ID", "")


def send_telegram_alert(message):
    """Gửi thông báo qua Telegram và in log phản hồi"""
    if not TELEGRAM_BOT_TOKEN or not TELEGRAM_CHAT_ID:
        logging.warning("Chưa cấu hình TELEGRAM_BOT_TOKEN hoặc TELEGRAM_CHAT_ID!")
        return
        
    url = f"https://api.telegram.org/bot{TELEGRAM_BOT_TOKEN}/sendMessage"
    payload = {"chat_id": TELEGRAM_CHAT_ID, "text": message, "parse_mode": "HTML"}
    
    try:
        response = requests.post(url, json=payload, timeout=5)
        res_data = response.json()
        if res_data.get("ok"):
            logging.info("Đã gửi thông báo Telegram vào Group thành công!")
        else:
            logging.error(f"Lỗi Telegram API: {res_data.get('description')}")
    except Exception as e:
        logging.error(f"Lỗi kết nối mạng khi gửi Telegram: {e}")


POLL_INTERVAL = 10

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    handlers=[
        logging.FileHandler(os.path.join(BASE_DIR, "automation.log")),
        logging.StreamHandler()
    ]
)


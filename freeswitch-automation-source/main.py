def auto_detect_locked_numbers(sheet_numbers, sheet_queue):
    try:
        numbers_records = sheet_numbers.get_all_records()
        queue_records = sheet_queue.get_all_records()
    except Exception as e:
        logging.error(f"Lỗi đọc dữ liệu Auto-Detect: {e}")
        return

    # Lấy danh sách số cũ đã có trong QUEUE (so sánh bằng clean_phone)
    existing_queue_old_numbers = [
        clean_phone(r.get("Old_Number", "")) 
        for r in queue_records 
        if r.get("Old_Number")
    ]

    now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    for n_row in numbers_records:
        phone = str(n_row.get("Phone", "")).strip()
        cleaned_phone = clean_phone(phone)
        fusion = str(n_row.get("Fusion", "")).strip()
        status = str(n_row.get("Status", "")).strip().upper()

        if status in ["LOCKED", "BLOCKED"] and phone and cleaned_phone not in existing_queue_old_numbers:
            new_id = len(queue_records) + 1
            logging.info(f"[Auto-Detect] Phát hiện số bị {status}: Phone={phone}, Fusion={fusion}. Tạo Job trong QUEUE...")
            
            new_row = [new_id, fusion, phone, "", status, "AUTO_1CLICK", "PENDING", 0, "", now_str]
            sheet_queue.append_row(new_row)
            existing_queue_old_numbers.append(cleaned_phone)

def process_replace_queue():
    try:
        doc = get_google_sheet()
        sheet_numbers = doc.worksheet("NUMBERS")
        sheet_queue = doc.worksheet("REPLACE_QUEUE")
        
        try:
            sheet_history = doc.worksheet("CHANGE_HISTORY")
        except Exception:
            sheet_history = None

    except Exception as e:
        logging.error(f"Lỗi kết nối Google Sheets API: {e}")
        return

    auto_detect_locked_numbers(sheet_numbers, sheet_queue)

    queue_records = sheet_queue.get_all_records()
    numbers_records = sheet_numbers.get_all_records()

    now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    for idx, row in enumerate(queue_records, start=2):
        if str(row.get("Status", "")).strip().upper() == "PENDING":
            job_id = row.get("ID")
            fusion = str(row.get("Fusion", "")).strip()
            old_number = str(row.get("Old_Number", "")).strip()
            cleaned_old_number = clean_phone(old_number)
            
            logging.info(f"Phát hiện Job PENDING: ID={job_id}, Fusion={fusion}, Old_Number={old_number}")

            sheet_queue.update_cell(idx, 7, "PROCESSING")
            sheet_queue.update_cell(idx, 10, now_str)

            host_ip = FUSION_NODES.get(fusion)
            if not host_ip:
                err = f"Không tìm thấy IP cho Fusion: {fusion}"
                logging.error(err)
                sheet_queue.update_cell(idx, 7, "FAILED")
                sheet_queue.update_cell(idx, 9, err)
                continue

            backups = []
            for n_idx, n_row in enumerate(numbers_records, start=2):
                if (str(n_row.get("Fusion")).strip() == fusion and 
                    str(n_row.get("Status")).strip().upper() == "BACKUP"):
                    try:
                        priority_val = int(n_row.get("Priority", 999))
                    except ValueError:
                        priority_val = 999
                    
                    backups.append({
                        "row_idx": n_idx,
                        "phone": str(n_row.get("Phone")).strip(),
                        "priority": priority_val
                    })

            if not backups:
                err = f"Hết số BACKUP cho {fusion}!"
                logging.error(err)
                sheet_queue.update_cell(idx, 7, "FAILED")
                sheet_queue.update_cell(idx, 9, err)
                send_telegram_alert(f"<b>ALERT WARNING:</b> {err}")
                continue

            backups.sort(key=lambda x: x["priority"])
            selected_backup = backups[0]
            new_number = selected_backup["phone"]
            backup_row_idx = selected_backup["row_idx"]

            active_numbers = []
            old_number_row_idx = None

            for n_idx, n_row in enumerate(numbers_records, start=2):
                p_phone = str(n_row.get("Phone")).strip()
                p_fusion = str(n_row.get("Fusion")).strip()
                p_status = str(n_row.get("Status")).strip().upper()

                if p_fusion == fusion:
                    if clean_phone(p_phone) == cleaned_old_number:
                        old_number_row_idx = n_idx
                    elif p_status == "ACTIVE":
                        active_numbers.append(p_phone)

            active_numbers.append(new_number)

            success, ssh_err = deploy_lua_to_freeswitch(host_ip, active_numbers)

            if success:
                # 1. Đảm bảo Số cũ -> LOCKED (hoặc giữ BLOCKED)
                if old_number_row_idx:
                    sheet_numbers.update_cell(old_number_row_idx, 8, now_str)

                # 2. Số mới (Backup) -> ACTIVE
                sheet_numbers.update_cell(backup_row_idx, 5, "ACTIVE")
                sheet_numbers.update_cell(backup_row_idx, 8, now_str)

                # 3. Cập nhật REPLACE_QUEUE -> SUCCESS
                sheet_queue.update_cell(idx, 4, new_number)
                sheet_queue.update_cell(idx, 7, "SUCCESS")
                sheet_queue.update_cell(idx, 9, "")
                sheet_queue.update_cell(idx, 10, now_str)

                # 4. Ghi log vào CHANGE_HISTORY
                if sheet_history:
                    reason = str(row.get("Reason", "BLOCKED"))
                    # Cột: Time | Fusion | Old_Number | New_Number | Reason | Status | User
                    history_row = [now_str, fusion, old_number, new_number, reason, "SUCCESS", "SYSTEM_BOT"]
                    sheet_history.append_row(history_row)

                msg = f"<b>ĐỔI SỐ THÀNH CÔNG [{fusion}]</b>\nOld: {old_number}\nNew: {new_number}\nHost: {host_ip}"
                logging.info(msg.replace("<b>", "").replace("</b>", ""))
                send_telegram_alert(msg)
            else:
                retry_count = int(row.get("Retry_Count", 0)) + 1
                sheet_queue.update_cell(idx, 4, new_number)
                sheet_queue.update_cell(idx, 7, "FAILED")
                sheet_queue.update_cell(idx, 8, retry_count)
                sheet_queue.update_cell(idx, 9, ssh_err)
                sheet_queue.update_cell(idx, 10, now_str)

                send_telegram_alert(f"<b>LỖI ĐỔI SỐ [{fusion}]</b>\nError: {ssh_err}")

# ==========================================
# 4. MAIN LOOP
# ==========================================
if __name__ == "__main__":
    logging.info("=== HỆ THỐNG FS CALLER ID AUTOMATION BẮT ĐẦU CHẠY ===")
    while True:
        try:
            process_replace_queue()
        except Exception as e:
            logging.error(f"Lỗi ngoài vòng lặp chính: {e}")
        
        time.sleep(POLL_INTERVAL)

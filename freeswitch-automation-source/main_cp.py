# 2. HÀM BỔ TRỢ (HELPER FUNCTIONS)
# ==========================================
def get_google_sheet():
    """Khởi tạo kết nối Google Sheets API"""
    scope = [
        "https://spreadsheets.google.com/feeds",
        "https://www.googleapis.com/auth/drive"
    ]
    creds = ServiceAccountCredentials.from_json_keyfile_name(CREDENTIALS_FILE, scope)
    client = gspread.authorize(creds)
    return client.open(SPREADSHEET_NAME)

def send_telegram_alert(message):
    """Gửi thông báo qua Telegram"""
    if not TELEGRAM_BOT_TOKEN or not TELEGRAM_CHAT_ID:
        return
    url = f"https://api.telegram.org/bot{TELEGRAM_BOT_TOKEN}/sendMessage"
    payload = {"chat_id": TELEGRAM_CHAT_ID, "text": message, "parse_mode": "HTML"}
    try:
        requests.post(url, json=payload, timeout=5)
    except Exception as e:
        logging.error(f"Lỗi gửi Telegram Alert: {e}")

def deploy_lua_to_freeswitch(host_ip, phone_numbers):
    """Tạo nội dung file Lua và SSH đẩy lên máy chủ FreeSWITCH"""
    # Sinh định dạng Lua Table
    numbers_str = ",\n    ".join([f'"{phone}"' for phone in phone_numbers])
    lua_content = f"""-- Auto-generated by Automation Script at {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}
return {{
    {numbers_str}
}}
"""
    
    ssh = paramiko.SSHClient()
    ssh.set_missing_host_key_policy(paramiko.AutoAddPolicy())
    
    try:
        ssh.connect(
            hostname=host_ip,
            username=SSH_USER,
            key_filename=SSH_KEY_PATH,
            timeout=10
        )
        sftp = ssh.open_sftp()
        with sftp.file(REMOTE_LUA_PATH, "w") as f:
            f.write(lua_content)
        sftp.close()
        ssh.close()
        logging.info(f"SSH Successful: Đã cập nhật file Lua lên {host_ip}")
        return True, ""
    except Exception as e:
        error_msg = f"SSH Error [{host_ip}]: {str(e)}"
        logging.error(error_msg)
        return False, error_msg


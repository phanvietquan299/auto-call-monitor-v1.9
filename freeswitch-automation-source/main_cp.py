import logging
import datetime
import paramiko
import gspread
import requests
import os
from oauth2client.service_account import ServiceAccountCredentials

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
CREDENTIALS_FILE = os.path.join(BASE_DIR, "credentials.json")

# ==========================================
# 1. CẤU HÌNH HỆ THỐNG
# ==========================================
# Cấu hình Google Sheet & Credentials
CREDENTIALS_FILE = "credentials.json"
SPREADSHEET_NAME = "PhoneReplace"  # Thay đúng tên file Google Sheet của bạn

# Danh sách IP của các Node FreeSWITCH
FUSION_NODES = {
    "FS01": "10.10.101.176",
    "FS02": "10.10.101.177",
    "FS03": "10.10.101.178"
}

# Cấu hình SSH
SSH_USER = "root"
SSH_KEY_PATH = "/root/.ssh/id_rsa"
REMOTE_LUA_PATH = "/usr/share/freeswitch/scripts/caller_ids.lua"  # Đường dẫn lưu file Lua trên FS

# Cấu hình Telegram Alert (Để trống nếu chưa dùng)
TELEGRAM_BOT_TOKEN = os.environ.get("TELEGRAM_BOT_TOKEN", "")
TELEGRAM_CHAT_ID = os.environ.get("TELEGRAM_CHAT_ID", "")

# Thời gian nghỉ giữa mỗi lần quét (giây)
POLL_INTERVAL = 10

# Cấu hình Logging
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    handlers=[
        logging.FileHandler("automation.log"),
        logging.StreamHandler()
    ]
)


# 3. CORE AUTOMATION ENGINE
# ==========================================
def process_replace_queue():
    """Hàm quét và xử lý yêu cầu đổi số trong QUEUE"""
    try:
        doc = get_google_sheet()
        sheet_numbers = doc.worksheet("NUMBERS")
        sheet_queue = doc.worksheet("REPLACE_QUEUE")
    except Exception as e:
        logging.error(f"Lỗi kết nối Google Sheets API: {e}")
        return

    # Lấy toàn bộ dữ liệu từ 2 sheet
    queue_records = sheet_queue.get_all_records()
    numbers_records = sheet_numbers.get_all_records()

    now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    # Tìm các hàng có Status == 'PENDING'
    for idx, row in enumerate(queue_records, start=2):  # start=2 vì hàng 1 là Header
        if str(row.get("Status", "")).strip().upper() == "PENDING":
            job_id = row.get("ID")
            fusion = row.get("Fusion")
            old_number = str(row.get("Old_Number")).strip()
            
            logging.info(f"Phát hiện Job PENDING: ID={job_id}, Fusion={fusion}, Old_Number={old_number}")

            # Đổi trạng thái Job thành PROCESSING
            sheet_queue.update_cell(idx, 7, "PROCESSING")  # Cột 7: Status
            sheet_queue.update_cell(idx, 10, now_str)      # Cột 10: Updated_At

            # Kiểm tra IP của Fusion Node
            host_ip = FUSION_NODES.get(fusion)
            if not host_ip:
                err = f"Không tìm thấy IP cho Fusion: {fusion}"
                logging.error(err)
                sheet_queue.update_cell(idx, 7, "FAILED")
                sheet_queue.update_cell(idx, 9, err)
                continue

            # Lọc danh sách số BACKUP của Fusion đó, sắp xếp theo Priority tăng dần
            backups = []
            for n_idx, n_row in enumerate(numbers_records, start=2):
                if (str(n_row.get("Fusion")) == fusion and 
                    str(n_row.get("Status")).strip().upper() == "BACKUP"):
                    try:
                        priority_val = int(n_row.get("Priority", 999))
                    except ValueError:
                        priority_val = 999
                    
                    backups.append({
                        "row_idx": n_idx,
                        "phone": str(n_row.get("Phone")).strip(),
                        "priority": priority_val
                    })

            if not backups:
                err = f"Hết số BACKUP cho {fusion}!"
                logging.error(err)
                sheet_queue.update_cell(idx, 7, "FAILED")
                sheet_queue.update_cell(idx, 9, err)
                send_telegram_alert(f"<b>ALERT WARNING:</b> {err}")
                continue

            # Chọn số BACKUP có Priority nhỏ nhất
            backups.sort(key=lambda x: x["priority"])
            selected_backup = backups[0]
            new_number = selected_backup["phone"]
            backup_row_idx = selected_backup["row_idx"]

            # Lập danh sách các số ACTIVE hiện tại của Fusion đó (sau khi đổi old_number -> new_number)
            active_numbers = []
            old_number_row_idx = None

            for n_idx, n_row in enumerate(numbers_records, start=2):
                p_phone = str(n_row.get("Phone")).strip()
                p_fusion = str(n_row.get("Fusion")).strip()
                p_status = str(n_row.get("Status")).strip().upper()

                if p_fusion == fusion:
                    if p_phone == old_number:
                        old_number_row_idx = n_idx
                    elif p_status == "ACTIVE":
                        active_numbers.append(p_phone)

            # Thêm số mới vào danh sách ACTIVE
            active_numbers.append(new_number)

            # Đẩy file Lua lên FreeSWITCH
            success, ssh_err = deploy_lua_to_freeswitch(host_ip, active_numbers)

            if success:
                # 1. Cập nhật Số cũ -> LOCKED
                if old_number_row_idx:
                    sheet_numbers.update_cell(old_number_row_idx, 5, "LOCKED")     # Cột 5: Status
                    sheet_numbers.update_cell(old_number_row_idx, 8, now_str)      # Cột 8: Updated_At

                # 2. Cập nhật Số mới -> ACTIVE
                sheet_numbers.update_cell(backup_row_idx, 5, "ACTIVE")             # Cột 5: Status
                sheet_numbers.update_cell(backup_row_idx, 8, now_str)              # Cột 8: Updated_At

                # 3. Cập nhật REPLACE_QUEUE -> SUCCESS
                sheet_queue.update_cell(idx, 4, new_number)                        # Cột 4: New_Number
                sheet_queue.update_cell(idx, 7, "SUCCESS")                         # Cột 7: Status
                sheet_queue.update_cell(idx, 9, "")                                # Cột 9: Error_Log
                sheet_queue.update_cell(idx, 10, now_str)                          # Cột 10: Updated_At

                msg = f"<b>ĐỔI SỐ THÀNH CÔNG [{fusion}]</b>\nOld: {old_number}\nNew: {new_number}\nHost: {host_ip}"
                logging.info(msg.replace("<b>", "").replace("</b>", ""))
                send_telegram_alert(msg)
            else:
                # Cập nhật REPLACE_QUEUE -> FAILED
                retry_count = int(row.get("Retry_Count", 0)) + 1
                sheet_queue.update_cell(idx, 4, new_number)
                sheet_queue.update_cell(idx, 7, "FAILED")
                sheet_queue.update_cell(idx, 8, retry_count)                       # Cột 8: Retry_Count
                sheet_queue.update_cell(idx, 9, ssh_err)                           # Cột 9: Error_Log
                sheet_queue.update_cell(idx, 10, now_str)

                send_telegram_alert(f"<b>LỖI ĐỔI SỐ [{fusion}]</b>\nError: {ssh_err}")

# ==========================================
# 4. VÒNG LẶP CHẠY CHÍNH (MAIN LOOP)
# ==========================================
if __name__ == "__main__":
    logging.info("=== HỆ THỐNG FS CALLER ID AUTOMATION BẮT ĐẦU CHẠY ===")
    while True:
        try:
            process_replace_queue()
        except Exception as e:
            logging.error(f"Lỗi ngoài vòng lặp chính: {e}")
        
        time.sleep(POLL_INTERVAL)
